#!/bin/bash
set -euo pipefail
project_dir="$(cd "$(dirname "$0")/.." && pwd)"
build_dir="${FOCUS_LENS_BUILD_DIR:-$project_dir/.build}"
output_dir="${1:-$project_dir/dist}"
mkdir -p "$output_dir"
mkdir -p "$build_dir/cache" "$build_dir/clang-cache"
export CLANG_MODULE_CACHE_PATH="${CLANG_MODULE_CACHE_PATH:-$build_dir/clang-cache}"
export SWIFTPM_MODULECACHE_OVERRIDE="${SWIFTPM_MODULECACHE_OVERRIDE:-$build_dir/clang-cache}"
output_dir="$(cd "$output_dir" && pwd)"
app_path="$output_dir/Focus Lens.app"
cd "$project_dir"
swift build -c release --scratch-path "$build_dir" --cache-path "$build_dir/cache" "${@:2}"
bin_path="$(swift build -c release --scratch-path "$build_dir" --cache-path "$build_dir/cache" --show-bin-path)"
mkdir -p "$app_path/Contents/MacOS" "$app_path/Contents/Resources"
cp "$bin_path/FocusLens" "$app_path/Contents/MacOS/FocusLens"
cp Resources/Info.plist "$app_path/Contents/Info.plist"
swift -module-cache-path "$build_dir/IconModuleCache" scripts/make-icon.swift "$build_dir/AppIcon.iconset"
iconutil -c icns "$build_dir/AppIcon.iconset" -o "$app_path/Contents/Resources/AppIcon.icns"
signing_dir="${FOCUS_LENS_SIGNING_DIR:-$HOME/Library/Application Support/FocusLens/Signing}"
python3 scripts/sign-local.py "$app_path" "$signing_dir"
codesign --verify --strict "$app_path"
printf '\nBuilt: %s\n' "$app_path"
